"""Build CUAD scale-curve libraries: the 12 gold PDFs (contracts/) plus N-12 distractor contracts taken from the
CUAD full_contract_txt files (plain text; ingesting 498 more PDFs through Docling is ~1 min/PDF on this CPU,
see RESULTS.txt). Distractors are chosen deterministically (sha256 order) and are nested: size 50 subset of 200
subset of 510. Also writes gold-cuad-scale.yaml = gold-cuad.yaml without the cross-contract (enumeration)
questions, which distractor contracts would legitimately contaminate.
Usage: make_scale_corpora.py CUAD_V1_DIR OUT_DIR"""
import hashlib, shutil, sys
from pathlib import Path
import yaml

cuad, out = Path(sys.argv[1]), Path(sys.argv[2])
here = Path(__file__).resolve().parent
gold_pdfs = sorted(p.name for p in (here.parent / "external/cuad/corpus/contracts").glob("*.pdf"))
gold_stems = {Path(n).stem for n in gold_pdfs}
txts = sorted((cuad / "full_contract_txt").glob("*.txt"), key=lambda p: hashlib.sha256(p.name.encode()).hexdigest())
dist = [p for p in txts if p.stem not in gold_stems]
print(len(gold_pdfs), "gold pdfs;", len(dist), "distractor txts")
for size in (12, 50, 200, 510):
    d = out / f"lib{size}"
    shutil.rmtree(d, ignore_errors=True)
    (d / "contracts").mkdir(parents=True)
    for n in gold_pdfs:
        shutil.copy2(here.parent / "external/cuad/corpus/contracts" / n, d / "contracts" / n)
    if size > 12:
        (d / "distractors").mkdir()
        for p in dist[: size - 12]:
            shutil.copy2(p, d / "distractors" / p.name)
g = yaml.safe_load((here.parent / "gold-cuad.yaml").read_text())
g["questions"] = [q for q in g["questions"] if not q.get("enumeration")]
hdr = "# gold-cuad.yaml minus cross-contract enumeration questions (distractor contracts contaminate those). GENERATED by make_scale_corpora.py\n"
(here.parent / "gold-cuad-scale.yaml").write_text(hdr + yaml.safe_dump(g, sort_keys=False, allow_unicode=True, width=110))
print(len(g["questions"]), "questions")
